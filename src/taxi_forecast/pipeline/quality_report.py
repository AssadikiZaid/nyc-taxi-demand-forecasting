"""Summarize the monthly JSON quality reports into ``docs/data_quality.md``.

Usage::

    python -m taxi_forecast.pipeline.quality_report
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from taxi_forecast.config import PROJECT_ROOT
from taxi_forecast.paths import default_data_dir

DEFAULT_OUTPUT = PROJECT_ROOT / "docs" / "data_quality.md"

RULE_COLUMNS = (
    ("exact_duplicate", "Exact duplicates"),
    ("pickup_outside_month", "Pickup outside month"),
    ("invalid_zone", "Invalid zone"),
    ("reversal_record", "Reversal records"),
    ("negative_duration", "Negative duration"),
    ("duration_too_long", "Duration too long"),
    ("no_ride", "No ride"),
    ("distance_too_long", "Distance too long"),
)


def load_reports(quality_dir: Path) -> list[dict[str, Any]]:
    """Return every monthly report found in ``quality_dir``, oldest month first."""
    return [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(quality_dir.glob("quality_*.json"))
    ]


def _percent(numerator: float, denominator: float) -> str:
    return f"{100 * numerator / denominator:.2f} %" if denominator else "n/a"


def render_markdown(reports: list[dict[str, Any]]) -> str:
    """Render the reports as a Markdown page with one table row per month and a total."""
    if not reports:
        raise ValueError("No quality report found: run the panel job first (`make panel`).")
    versions = sorted({report.get("rules_version", 1) for report in reports})
    if len(versions) > 1:
        raise ValueError(
            f"The reports were built with different rule versions {versions}: "
            "rebuild every month with `make panel` before summarizing them."
        )

    thresholds = reports[-1]["thresholds"]
    header = ["Month", "Raw trips", *[label for _, label in RULE_COLUMNS]]
    header += ["Kept", "Kept share", "Zero cells", "Peak hour", "Quietest hour"]
    lines = [
        "# Data quality",
        "",
        "Generated by `make quality-report` from the JSON reports of the panel job "
        f"(rules version {versions[0]}). Do not edit by hand.",
        "",
        "Each trip is counted under the first rule it breaks, in the column order below:",
        "",
        "- **Reversal records**: a negative fare whose trip also appears with the opposite",
        "  fare (same vendor, times and zones); the original trip is kept, so the pickup is",
        "  counted once.",
        "- **Negative duration**: dropoff before pickup (clock error).",
        f"- **Duration too long**: more than {thresholds['max_duration_hours']} hours.",
        "- **No ride**: the taxi did not move and the meter ran for less than",
        f"  {thresholds.get('min_ride_seconds', 60)} seconds.",
        f"- **Distance too long**: more than {thresholds['max_trip_distance_miles']} miles.",
        "",
        "Peak and quietest hours are New York wall-clock hours of pickups: they check that",
        "TLC timestamps are local time. The reasons behind each rule are in",
        "[decisions.md](decisions.md) (D-011 and D-013).",
        "",
        "| " + " | ".join(header) + " |",
        "|" + "|".join(" --- " for _ in header) + "|",
    ]

    totals = {"rows_raw": 0, "rows_kept": 0, "zero": 0, "cells": 0}
    totals.update({rule: 0 for rule, _ in RULE_COLUMNS})
    for report in reports:
        profile = report["pickups_by_local_hour"]
        peak = max(range(24), key=profile.__getitem__)
        quietest = min(range(24), key=profile.__getitem__)
        zero_cells = round(report["panel"]["zero_cell_share"] * report["panel"]["rows"])
        row = [
            report["month"],
            f"{report['rows_raw']:,}",
            *[f"{report['rejected'][rule]:,}" for rule, _ in RULE_COLUMNS],
            f"{report['rows_kept']:,}",
            _percent(report["rows_kept"], report["rows_raw"]),
            _percent(zero_cells, report["panel"]["rows"]),
            f"{peak:02d}:00",
            f"{quietest:02d}:00",
        ]
        lines.append("| " + " | ".join(row) + " |")
        totals["rows_raw"] += report["rows_raw"]
        totals["rows_kept"] += report["rows_kept"]
        totals["zero"] += zero_cells
        totals["cells"] += report["panel"]["rows"]
        for rule, _ in RULE_COLUMNS:
            totals[rule] += report["rejected"][rule]

    total_row = [
        "**Total**",
        f"{totals['rows_raw']:,}",
        *[f"{totals[rule]:,}" for rule, _ in RULE_COLUMNS],
        f"{totals['rows_kept']:,}",
        _percent(totals["rows_kept"], totals["rows_raw"]),
        _percent(totals["zero"], totals["cells"]),
        "",
        "",
    ]
    lines.append("| " + " | ".join(total_row) + " |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data-dir", type=Path, default=default_data_dir())
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    reports = load_reports(args.data_dir / "quality")
    args.output.write_text(render_markdown(reports), encoding="utf-8")
    print(f"Wrote {args.output} ({len(reports)} month(s))")


if __name__ == "__main__":
    main()
